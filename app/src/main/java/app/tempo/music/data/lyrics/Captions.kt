package app.tempo.music.data.lyrics

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.longOrNull
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull

/** One of a YouTube video's caption tracks. */
data class CaptionTrack(val url: String, val languageTag: String, val autoGenerated: Boolean)

/**
 * Lyrics from a music video's own captions. Official videos often have the lyrics as captions,
 * timed by hand to that exact video.
 */
object Captions {
    private val json = Json { ignoreUnknownKeys = true }
    private val musicNotes = Regex("""^[\s♪♫♬♩]+|[\s♪♫♬♩]+$""")
    /** "[Music]", "(applause)" and the like aren't lyrics. */
    private val soundOnly = Regex("""^[\[(].*[\])]$""")

    /** The same captions in YouTube's JSON format, which keeps exact times. */
    fun json3Url(url: String): String =
        url.toHttpUrlOrNull()?.newBuilder()?.setQueryParameter("fmt", "json3")?.build()?.toString() ?: url

    fun parseJson3(text: String): List<LyricLine> {
        val root = json.parseToJsonElement(text) as? JsonObject ?: return emptyList()
        val events = root["events"] as? JsonArray ?: return emptyList()
        val lines = events.mapNotNull { e ->
            val event = e as? JsonObject ?: return@mapNotNull null
            val start = event["tStartMs"]?.jsonPrimitive?.longOrNull ?: return@mapNotNull null
            val segs = event["segs"] as? JsonArray ?: return@mapNotNull null
            val words = segs.joinToString("") { (it as? JsonObject)?.get("utf8")?.jsonPrimitive?.contentOrNull.orEmpty() }
                .replace('\n', ' ')
                .replace(musicNotes, "")
                .replace(Regex("\\s+"), " ")
                .trim()
            if (words.isEmpty() || soundOnly.matches(words)) null else LyricLine(start, words)
        }
        // ALL-CAPS captions read better in sentence case.
        val allCaps = lines.all { it.text == it.text.uppercase() } && lines.any { it.text.any(Char::isLetter) }
        return if (!allCaps) lines else lines.map { line ->
            line.copy(text = line.text.lowercase().replaceFirstChar { it.uppercase() })
        }
    }

    /** Share of [lines]' words that also appear in [reference] (0–1). */
    fun overlap(lines: List<LyricLine>, reference: String): Double {
        fun words(s: String) = s.lowercase()
            .map { if (it.isLetterOrDigit() || it == '\'') it else ' ' }
            .joinToString("")
            .split(' ')
            .filter { it.length > 1 }
        val known = words(reference).toHashSet()
        val captionWords = lines.flatMap { words(it.text) }
        if (captionWords.isEmpty()) return 0.0
        return captionWords.count { it in known }.toDouble() / captionWords.size
    }
}
